"""EntityQuestions analysis (rules fixed before the runs, as described in the paper).

Usage:  python scripts/analysis/entityquestions.py
- Facts: the 3,994 test questions of the 18 relations outside PopQA (principal set), dense-known per model (the dense
  model's answer matches); the 600 questions of the 6 shared relations are reported separately.
- (a) Transfer: paper calibration (PopQA graph) scored on EntityQuestions. (b) Replication: calibration on the
  EntityQuestions graph. Paired differences with 10,000 bootstrap draws over test facts (one draw shared by all
  runs), Holm counts per contrast family.
- Truth in (b): true minus counterfactual (declarative and question-answer), three calibration samples; pooled over
  the 48 differences with the two-level bootstrap (facts shared, samples within setting); equivalence is claimed only
  if the 90% interval lies inside (-1.5, +1.5).
Writes outputs/tables/entityquestions.json and outputs/reports/entityquestions.md.
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kgcal import paths as P            # noqa: E402
R = P.EQ_RESULTS
PAPER = [("qwen15b", "Qwen2.5-1.5B"), ("olmo1b", "OLMo-2-1B"), ("qwen7b", "Qwen2.5-7B"), ("olmo7b", "OLMo-2-7B")]
NEW = [("llama8b", "Llama-3.1-8B"), ("mistral7b", "Mistral-7B-v0.3"), ("phi4", "Phi-4")]
MODELS = PAPER + NEW
GROUPS = {"paper": [t for t, _ in PAPER], "new": [t for t, _ in NEW]}
BUDGETS = ("0.7", "0.5")
NB, MARGIN = 10000, 1.5
facts = json.loads((P.EQ / "eq_test_sample.json").read_text())["facts"]
SHARED = np.array([f["shared_with_popqa"] for f in facts])
nT = len(facts)
bits = lambda p: {k: np.array([c == "1" for c in v["eq"]], bool) for k, v in json.loads(p.read_text()).items()}
A = {t: bits(R / f"{t}_eq_bits.json") for t, _ in MODELS if (R / f"{t}_eq_bits.json").exists()}
B = {t: {s: bits(p) for s in (0, 1, 2)
         if (p := R / (f"{t}_eqb_bits.json" if s == 0 else f"{t}_eqb_cs{s}_bits.json")).exists()} for t, _ in MODELS}
PENDING = [f"EntityQuestions (a) {t}" for t, _ in MODELS if t not in A]
PENDING += [f"EntityQuestions (b) {t} sample {s}" for t, _ in MODELS for s in (0, 1, 2) if s not in B[t]]
MODELS = [(t, l) for t, l in MODELS if t in A]
DENSE = {t: A[t]["1.0|dense"] for t, _ in MODELS}

rng = np.random.default_rng(0)
WB = np.empty((NB, nT), np.float32)
for b0 in range(0, NB, 1000):
    WB[b0:b0 + 1000] = np.stack([np.bincount(r, minlength=nT) for r in rng.integers(0, nT, size=(1000, nT))])


def boot(a, b, mask):
    d = np.where(mask, b.astype(np.float32) - a.astype(np.float32), 0)
    return 100 * float(d[mask].mean()), 100 * (WB @ d) / (WB @ mask.astype(np.float32))


def summ(est, reps):
    lo, hi = np.quantile(reps, [0.025, 0.975]); lo90, hi90 = np.quantile(reps, [0.05, 0.95])
    p = max(min(1.0, 2 * min((reps <= 0).mean(), (reps >= 0).mean())), 1 / NB)
    return {"diff": est, "lo": float(lo), "hi": float(hi), "lo90": float(lo90), "hi90": float(hi90), "p": float(p),
            "sig": bool(lo > 0 or hi < 0)}


def holm(ps):
    rej, order = np.zeros(len(ps), bool), np.argsort(ps)
    for r, i in enumerate(order):
        if ps[i] > 0.05 / (len(ps) - r):
            break
        rej[i] = True
    return rej


f = lambda d: f"{'**' if d['sig'] else ''}{d['diff']:+.1f}{'**' if d['sig'] else ''}"
OUT, MD = {}, ["# EntityQuestions results (generated by scripts/analysis/entityquestions.py; do not edit)", "",
               "Retention differences in points on dense-known test facts; bold: 95% bootstrap interval excludes zero.", ""]
MD += ["| model | dense-known (new relations) | dense-known (shared relations) |", "|---|---|---|"]
for t, lab in MODELS:
    MD.append(f"| {lab} | {int((DENSE[t] & ~SHARED).sum())} | {int((DENSE[t] & SHARED).sum())} |")
MD.append("")
FAM_A = {"C4 repair vs none": ("none|C4", "C4|C4"), "Repair channel": ("C4|C4", "C4|MIX:KG-D"),
         "Selection, no repair (vs none)": ("none|C4", "MIX:KG-D|none"), "Both channels": ("C4|C4", "MIX:KG-D|MIX:KG-D"),
         "Truth (declarative)": ("MIX:KG-D~|MIX:KG-D~", "MIX:KG-D|MIX:KG-D")}
FAM_B = {"Repair channel": ("C4|C4", "C4|MIX:EQ-D"), "Selection, no repair (vs C4/C4)": ("C4|C4", "MIX:EQ-D|none"),
         "Both channels": ("C4|C4", "MIX:EQ-D|MIX:EQ-D"), "Truth (declarative)": ("MIX:EQ-D~|MIX:EQ-D~", "MIX:EQ-D|MIX:EQ-D"),
         "Truth (question-answer)": ("MIX:EQ-QA~|MIX:EQ-QA~", "MIX:EQ-QA|MIX:EQ-QA"),
         "Format (QA - declarative)": ("MIX:EQ-D|MIX:EQ-D", "MIX:EQ-QA|MIX:EQ-QA")}
for part, fam, src in (("a", FAM_A, lambda t: A[t]), ("b", FAM_B, lambda t: B[t].get(0))):
  for group, gtags in GROUPS.items():
    gmodels = [(t, l) for t, l in MODELS if t in gtags and src(t) is not None]
    if not gmodels:
        continue
    for grp, gm in (("new relations", ~SHARED), ("shared relations", SHARED)):
        MD += [f"## ({part}) {'transfer, PopQA graph' if part == 'a' else 'replication, EntityQuestions graph'}: {grp}, {group} models", "",
               "| contrast | " + " | ".join(f"{lab} {int(100 * float(b))}%" for _, lab in gmodels for b in BUDGETS)
               + " | sig. +/- | Holm +/- |", "|---|" + "---|" * (len(gmodels) * len(BUDGETS) + 2)]
        for name, (x, y) in fam.items():
            res = []
            for t, _ in gmodels:
                d = src(t)
                for b in BUDGETS:
                    if part == "b" and x == "C4|C4":
                        xa = d[f"{b}|{x}"]
                    else:
                        xa = d[f"{b}|{x}"]
                    res.append(summ(*boot(xa, d[f"{b}|{y}"], DENSE[t] & gm)))
            rej = holm(np.array([r["p"] for r in res]))
            sp, sn = sum(r["sig"] and r["diff"] > 0 for r in res), sum(r["sig"] and r["diff"] < 0 for r in res)
            hp = sum(j and r["diff"] > 0 for j, r in zip(rej, res)); hn = sum(j and r["diff"] < 0 for j, r in zip(rej, res))
            OUT[f"{part}|{grp}|{group}|{name}"] = {"cells": res, "sig_pos": sp, "sig_neg": sn, "holm_pos": int(hp), "holm_neg": int(hn)}
            MD.append(f"| {name} | " + " | ".join(f(r) for r in res) + f" | {sp}/{sn} | {hp}/{hn} |")
        MD.append("")

# truth over three samples, two-level bootstrap, new relations; per group, only models with all three samples
COMPLETE = [t for t, _ in MODELS if all(s in B[t] for s in (0, 1, 2))]
CELLS = [(t, b) for t in COMPLETE for b in BUDGETS]
SAMP = np.random.default_rng(1).integers(0, 3, size=(NB, max(1, len(CELLS)), 3))
rep, est = {}, {}
for t, b in CELLS:
    for fmt, (cf, tr) in (("decl", ("EQ-D~", "EQ-D")), ("qa", ("EQ-QA~", "EQ-QA"))):
        es, rs = [], []
        for s in (0, 1, 2):
            e, r = boot(B[t][s][f"{b}|MIX:{cf}|MIX:{cf}"], B[t][s][f"{b}|MIX:{tr}|MIX:{tr}"], DENSE[t] & ~SHARED)
            es.append(e); rs.append(r)
        est[(t, b, fmt)], rep[(t, b, fmt)] = np.array(es), np.stack(rs, 1)


def two_level(keys):
    e = float(np.mean([est[k].mean() for k in keys]))
    r = np.zeros(NB)
    for k in keys:
        pick = SAMP[:, CELLS.index((k[0], k[1])), :]
        r += np.take_along_axis(rep[k], pick, 1).mean(1)
    return summ(e, r / len(keys))


MD += ["## Truth in the replication over three calibration samples (new relations)", "",
       "| model | budget | declarative (samples) | question-answer (samples) |", "|---|---|---|---|"]
PER = {}
for t, b in CELLS:
    d, q = two_level([(t, b, "decl")]), two_level([(t, b, "qa")])
    PER[f"{t}|{b}"] = {"decl": d | {"samples": est[(t, b, "decl")].tolist()}, "qa": q | {"samples": est[(t, b, "qa")].tolist()}}
    MD.append(f"| {dict(MODELS)[t]} | {int(100 * float(b))}% | {f(d)} ({', '.join(f'{x:+.1f}' for x in est[(t, b, 'decl')])}) | "
              f"{f(q)} ({', '.join(f'{x:+.1f}' for x in est[(t, b, 'qa')])}) |")
POOL = {}
for group, gtags in GROUPS.items():
    if not all(t in COMPLETE for t in gtags):
        POOL[group] = "pending"
        continue
    gc = [(t, b) for t, b in CELLS if t in gtags]
    for name, keys in (("all", [(t, b, m) for t, b in gc for m in ("decl", "qa")]),
                       ("decl", [(t, b, "decl") for t, b in gc]), ("qa", [(t, b, "qa") for t, b in gc]),
                       ("small", [(t, b, m) for t, b in gc if t in ("qwen15b", "olmo1b") for m in ("decl", "qa")]),
                       ("large", [(t, b, m) for t, b in gc if t not in ("qwen15b", "olmo1b") for m in ("decl", "qa")])):
        if not keys:
            continue
        v = two_level(keys)
        v["runs"] = 3 * len(keys)
        v["equivalent_within_margin"] = bool(-MARGIN < v["lo90"] and v["hi90"] < MARGIN)
        v["smallest_margin_rejected"] = float(max(abs(v["lo90"]), abs(v["hi90"])))
        POOL[f"{group}|{name}"] = v
OUT["truth_pooled"] = POOL
OUT["truth_per_setting"] = PER
OUT["pending"] = PENDING
OUT["dense_known"] = {t: {"new": int((DENSE[t] & ~SHARED).sum()), "shared": int((DENSE[t] & SHARED).sum())} for t, _ in MODELS}
MD += ["", "| pooled | runs | mean | 95% interval | 90% interval | equivalent within 1.5 (pre-registered)? |",
       "|---|---|---|---|---|---|"]
for name, v in POOL.items():
    if v == "pending":
        MD.append(f"| {name} | pending | | | | |")
        continue
    MD.append(f"| {name} | {v['runs']} | {v['diff']:+.2f} | {v['lo']:+.2f} to {v['hi']:+.2f} | {v['lo90']:+.2f} to {v['hi90']:+.2f} | "
              f"{'yes' if v['equivalent_within_margin'] else 'no'} |")
MD += ["", "Pending runs: " + (", ".join(PENDING) or "none"), ""]
(P.TABLES / "entityquestions.json").write_text(json.dumps(OUT, indent=1))
(P.REPORTS / "entityquestions.md").write_text("\n".join(MD) + "\n")
print("\n".join(MD))
