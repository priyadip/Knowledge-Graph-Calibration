# how many facts two independently drawn sets share inside the knowledge-graph half of a mixture (32,768 tokens)
def _overlap(model_id):
    from transformers import AutoTokenizer
    tok = AutoTokenizer.from_pretrained(model_id)
    cal = D.facts_by_split(rows, split)["cal"]
    pset = {D.cloze(r["prop"], r["subj"]) for r in cal}

    def key_decl(x):
        w_ = x.rstrip(".").split(" ")
        for i in range(len(w_) - 1, 0, -1):
            if " ".join(w_[:i]) in pset:
                return " ".join(w_[:i])

    def half(lines):
        n, out = 0, []
        for x in lines:
            out.append(x); n += len(tok(x + "\n", add_special_tokens=False)["input_ids"])
            if n >= 64 * 512:
                return out
        return out
    lines = lambda name: [json.loads(l) for l in open(D.CALIB / f"{name}.jsonl")]   # original, independently shuffled files
    res = {}
    for a, b, kf in (("KG-D", "KG-D~", key_decl), ("KG-QA", "KG-QA~", lambda x: x.split(" A: ")[0])):
        A, B = {kf(x) for x in half(lines(a))}, {kf(x) for x in half(lines(b))}
        res[a] = len(A & B) / len(A); res[a + " facts"] = len(A)
    return res


