# ---------------------------------------------------------------- helpers
def load(d: Path, stem: str):
    p, b = d / f"{stem}.jsonl", d / f"{stem}_bits.json"
    if not p.exists():
        return None, None
    recs = {}
    for line in open(p):
        r = json.loads(line)
        recs[f"{r['target']}|{r['cond']}"] = r
    bits = {k: {f: np.array([c == "1" for c in v[f]], bool) for f in v} for k, v in json.loads(b.read_text()).items()}
    return recs, bits


def paired(a, b, mask, n_boot=10000, seed=0):
    """Mean of b minus a over facts in mask, paired bootstrap 95% CI, McNemar exact p."""
    x, y = a[mask].astype(float), b[mask].astype(float)
    rng = np.random.default_rng(seed)
    idx = rng.integers(0, len(x), size=(n_boot, len(x)))
    diffs = (y[idx] - x[idx]).mean(1)
    up, down = int(((~a) & b & mask).sum()), int((a & (~b) & mask).sum())
    p = binomtest(up, up + down, 0.5).pvalue if up + down else 1.0
    d = {"diff": float(y.mean() - x.mean()), "lo": float(np.quantile(diffs, 0.025)), "hi": float(np.quantile(diffs, 0.975)),
         "p": float(p)}
    d["sig"] = d["lo"] > 0 or d["hi"] < 0
    return d


def ret(bits, key, dense):
    return float(bits[key]["test_q"][dense].mean())


def num(name, value, sign=False, nd=1, pct=False):
    """Register a LaTeX macro. Signed values become math with a proper minus sign."""
    if isinstance(value, str):
        NUM[name] = value
        return value
    v = round(float(value), nd)
    s = f"{v:+.{nd}f}" if sign else f"{v:.{nd}f}"
    if s.lstrip("+-") == f"{0:.{nd}f}":
        s = f"{0:.{nd}f}"                                       # no signed zero
    NUM[name] = f"\\ensuremath{{{s}}}" if (sign or v < 0) else s
    return s


def sci(x):
    """1.2e-07 -> \\ensuremath{1.2\\times10^{-7}}"""
    m, e = f"{x:.1e}".split("e")
    return f"\\ensuremath{{{m}\\times10^{{{int(e)}}}}}"


def rng(vals, sign=False, nd=1):
    vals = [round(float(v), nd) for v in vals]
    return min(vals), max(vals)


def nfmt(v, sign=False, nd=1):
    s = f"{v:+.{nd}f}" if sign else f"{v:.{nd}f}"
    return f"\\ensuremath{{{s}}}" if (sign or v < 0) else s


def num_range(name, vals, sign=False, nd=1):
    lo, hi = rng(vals, sign, nd)
    NUM[name + "Lo"], NUM[name + "Hi"] = nfmt(lo, sign, nd), nfmt(hi, sign, nd)
    return lo, hi


def count_words(n):
    w = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten", "eleven", "twelve"]
    return w[n] if 0 <= n < len(w) else str(n)


