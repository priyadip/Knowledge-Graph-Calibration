"""Statistics that need no GPU, over the seven models (rules fixed before the runs, as described in the paper).

Usage:  python scripts/analysis/stats.py
1. Format by query type: question-answer minus declarative calibration (both channels, sample 0) with question and
   with cloze queries, the main effect (mean of the two) and the interaction (question minus cloze), per setting and
   pooled. Each query type uses its own dense-known mask; one bootstrap draw of test facts serves every term and
   every setting, because all runs score the same test facts.
2. Truth per setting over the three calibration samples, with the two-level bootstrap of paper_models.py 4b, and the
   pooled truth effect of the further families tested against the pre-registered margin of 1.5 points.
3. Holm counts (family-wise 5%) for every contrast family, beside the uncorrected counts.
Reads results/merged (Qwen2.5, OLMo-2) and results/families (Llama-3.1, Mistral, Phi-4). Writes
outputs/tables/stats.json and outputs/reports/stats.md.
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kgcal import paths as P            # noqa: E402
PAPER = [("qwen15b", "Qwen2.5-1.5B"), ("olmo1b", "OLMo-2-1B"), ("qwen7b", "Qwen2.5-7B"), ("olmo7b", "OLMo-2-7B")]
NEW = [("llama8b", "Llama-3.1-8B"), ("mistral7b", "Mistral-7B-v0.3"), ("phi4", "Phi-4")]
ALL = PAPER + NEW
LABEL = dict(ALL)
BUDGETS = (0.7, 0.5)
K = {"none": "none|C4", "c4": "C4|C4", "rep": "C4|MIX:KG-D", "sel": "MIX:KG-D|C4", "selnone": "MIX:KG-D|none",
     "both": "MIX:KG-D|MIX:KG-D", "qa": "MIX:KG-QA|MIX:KG-QA", "dcf": "MIX:KG-D~|MIX:KG-D~", "qacf": "MIX:KG-QA~|MIX:KG-QA~",
     "syn": "MIX:KG-S|MIX:KG-S", "wiki": "MIX:WIKI|MIX:WIKI", "other": "MIX:KG-O2|MIX:KG-O2", "anch": "MIX:KG-Ac|MIX:KG-Ac"}
NB = 10000
MARGIN = 1.5


def bits_of(tag, seed=0):
    d = P.MERGED if tag in dict(PAPER) else P.FAMILIES
    stem = tag if seed == 0 else f"{tag}_cs{seed}"
    raw = json.loads((d / f"{stem}_bits.json").read_text())
    return {k: {f: np.array([c == "1" for c in v[f]], bool) for f in v} for k, v in raw.items()}


B = {tag: {s: bits_of(tag, s) for s in (0, 1, 2)} for tag, _ in ALL}
# paired variants with cloze queries for the paper models come from the cloze reruns
PC = {}
for tag, _ in PAPER:
    raw = json.loads((P.PAIRED_CLOZE / f"{tag}_pc_bits.json").read_text())
    PC[tag] = {k: {f: np.array([c == "1" for c in v[f]], bool) for f in v} for k, v in raw.items()}
nT = len(B["qwen15b"][0]["1.0|dense"]["test_q"])
assert all(len(B[t][0]["1.0|dense"]["test_q"]) == nT for t, _ in ALL), "all models must score the same test facts"
DQ = {tag: B[tag][0]["1.0|dense"]["test_q"] for tag, _ in ALL}
DC = {tag: B[tag][0]["1.0|dense"]["test_c"] for tag, _ in ALL}
CELLS = [(tag, t) for tag, _ in ALL for t in BUDGETS]
PCELLS = [c for c in CELLS if c[0] in dict(PAPER)]
NCELLS = [c for c in CELLS if c[0] in dict(NEW)]

rng = np.random.default_rng(0)
WB = np.empty((NB, nT), np.float32)                     # bootstrap weights of test facts, shared by everything
for b0 in range(0, NB, 1000):
    idx = rng.integers(0, nT, size=(1000, nT))
    WB[b0:b0 + 1000] = np.stack([np.bincount(r, minlength=nT) for r in idx])


def boot_diff(a, b, mask):
    """100 x mean of b - a over mask: point estimate and NB bootstrap replicates (shared fact draws)."""
    d = np.where(mask, b.astype(np.float32) - a.astype(np.float32), 0)
    m = mask.astype(np.float32)
    return 100 * float(d[mask].mean()), 100 * (WB @ d) / (WB @ m)


def summarize(est, reps):
    lo, hi = np.quantile(reps, [0.025, 0.975])
    lo90, hi90 = np.quantile(reps, [0.05, 0.95])
    p = min(1.0, 2 * min((reps <= 0).mean(), (reps >= 0).mean()))
    return {"diff": est, "lo": float(lo), "hi": float(hi), "lo90": float(lo90), "hi90": float(hi90),
            "p": max(float(p), 1 / NB), "sig": bool(lo > 0 or hi < 0)}


def holm(ps, alpha=0.05):
    """Holm step-down: which hypotheses are rejected at family-wise alpha."""
    order = np.argsort(ps)
    rej = np.zeros(len(ps), bool)
    for r, i in enumerate(order):
        if ps[i] <= alpha / (len(ps) - r):
            rej[i] = True
        else:
            break
    return rej


def cloze_bits(tag, t, c):
    key = f"{t}|{K[c]}"
    if tag in PC and c in ("dcf", "qacf", "syn"):
        return PC[tag][key]["test_c"]
    return B[tag][0][key]["test_c"]


OUT, MD = {}, ["# Statistics (generated by scripts/analysis/stats.py; do not edit)", ""]

# ---------------------------------------------------------------- 1. format by query type
fq, reps_int = {}, {}
for tag, t in CELLS:
    b0 = B[tag][0]
    eq, rq = boot_diff(b0[f"{t}|{K['both']}"]["test_q"], b0[f"{t}|{K['qa']}"]["test_q"], DQ[tag])
    ec, rc = boot_diff(cloze_bits(tag, t, "both"), cloze_bits(tag, t, "qa"), DC[tag])
    fq[(tag, t)] = {"question": summarize(eq, rq), "cloze": summarize(ec, rc),
                    "main": summarize((eq + ec) / 2, (rq + rc) / 2), "interaction": summarize(eq - ec, rq - rc)}
    reps_int[(tag, t)] = (rq, rc)


def pooled(cells, f):
    est = float(np.mean([f(*[fq[c][q]["diff"] for q in ("question", "cloze")]) for c in cells]))
    reps = np.mean([f(*reps_int[c]) for c in cells], 0)
    return summarize(est, reps)


POOL = {}
for name, cells in (("all", CELLS), ("paper", PCELLS), ("new", NCELLS),
                    ("small", [c for c in CELLS if c[0] in ("qwen15b", "olmo1b")]),
                    ("large", [c for c in CELLS if c[0] not in ("qwen15b", "olmo1b")])):
    POOL[name] = {"interaction": pooled(cells, lambda q, c: q - c), "main": pooled(cells, lambda q, c: (q + c) / 2),
                  "question": pooled(cells, lambda q, c: q), "cloze": pooled(cells, lambda q, c: c)}
n_int_pos = sum(fq[c]["interaction"]["diff"] > 0 for c in CELLS)
claim_dep = n_int_pos >= 11 and POOL["all"]["interaction"]["lo"] > 0
OUT["format_query"] = {"cells": {f"{tag}|{t}": v for (tag, t), v in fq.items()}, "pooled": POOL,
                       "interaction_positive": int(n_int_pos), "rule_met_format_depends_on_query": bool(claim_dep)}
MD += ["## 1. Format by query type (question-answer minus declarative, both channels, sample 0)", "",
       "| model | budget | question queries | cloze queries | main effect | interaction (question - cloze) |",
       "|---|---|---|---|---|---|"]
f = lambda d: f"{'**' if d['sig'] else ''}{d['diff']:+.1f}{'**' if d['sig'] else ''} [{d['lo']:+.1f}, {d['hi']:+.1f}]"
for tag, t in CELLS:
    v = fq[(tag, t)]
    MD.append(f"| {LABEL[tag]} | {int(100 * t)}% | {f(v['question'])} | {f(v['cloze'])} | {f(v['main'])} | "
              f"{f(v['interaction'])} |")
MD += ["", "| pooled over | question | cloze | main effect | interaction |", "|---|---|---|---|---|"]
for name, v in POOL.items():
    MD.append(f"| {name} | {f(v['question'])} | {f(v['cloze'])} | {f(v['main'])} | {f(v['interaction'])} |")
holm_int = holm(np.array([fq[c]["interaction"]["p"] for c in CELLS]))
MD += ["", f"Interaction positive in {n_int_pos} of {len(CELLS)} settings, significant in "
       f"{sum(fq[c]['interaction']['sig'] and fq[c]['interaction']['diff'] > 0 for c in CELLS)} (Holm: "
       f"{int(holm_int.sum())}). Pre-registered rule for 'the format effect depends on the query type' "
       f"(>= 11 of 14 positive and pooled interval above zero): {'met' if claim_dep else 'NOT met'}.",
       "Question-answer text significantly better with question queries in: "
       + (", ".join(f"{LABEL[tag]} {int(100 * t)}%" for tag, t in CELLS
                    if fq[(tag, t)]["question"]["sig"] and fq[(tag, t)]["question"]["diff"] > 0) or "none") + ".", ""]

# ---------------------------------------------------------------- 2. truth per setting and pooled (two-level)
TRUTH, cellrep = {}, {}
for tag, t in CELLS:
    for fmt, (cf, tr) in (("decl", ("dcf", "both")), ("qa", ("qacf", "qa"))):
        ests, reps = [], []
        for s in (0, 1, 2):
            b = B[tag][s]
            e, r = boot_diff(b[f"{t}|{K[cf]}"]["test_q"], b[f"{t}|{K[tr]}"]["test_q"], DQ[tag])
            ests.append(e); reps.append(r)
        cellrep[(tag, t, fmt)] = (np.array(ests), np.stack(reps, 1))
rs = np.random.default_rng(1)
SAMP = rs.integers(0, 3, size=(NB, len(CELLS), 3))      # calibration samples resampled within each setting


def two_level(keys):
    """Mean over the given (tag, t, fmt) runs of the 3-sample means; facts shared, samples within setting."""
    est = float(np.mean([cellrep[k][0].mean() for k in keys]))
    reps = np.zeros(NB)
    for k in keys:
        ci = CELLS.index((k[0], k[1]))
        pick = SAMP[:, ci, :]
        reps += np.take_along_axis(cellrep[k][1], pick, 1).mean(1)
    return summarize(est, reps / len(keys))


per = {}
for tag, t in CELLS:
    for fmt in ("decl", "qa"):
        per[(tag, t, fmt)] = two_level([(tag, t, fmt)]) | {"samples": [float(x) for x in cellrep[(tag, t, fmt)][0]]}
TP = {}
for name, cells in (("paper", PCELLS), ("new", NCELLS), ("all", CELLS)):
    keys = [(tag, t, fmt) for tag, t in cells for fmt in ("decl", "qa")]
    TP[name] = two_level(keys)
    TP[name]["eq_bound_smallest"] = float(max(abs(TP[name]["lo90"]), abs(TP[name]["hi90"])))
    TP[name]["equivalent_at_margin"] = bool(-MARGIN < TP[name]["lo90"] and TP[name]["hi90"] < MARGIN)
    for fmt in ("decl", "qa"):
        TP[f"{name}_{fmt}"] = two_level([(tag, t, fmt) for tag, t in cells])
paper_check = TP["paper"]
OUT["truth"] = {"cells": {f"{a}|{b}|{c}": v for (a, b, c), v in per.items()}, "pooled": TP, "margin": MARGIN}
MD += ["## 2. Truth effect per setting (true minus counterfactual, mean of three calibration samples)", "",
       "| model | budget | declarative | question-answer | samples (decl.) | samples (QA) |", "|---|---|---|---|---|---|"]
for tag, t in CELLS:
    d, q = per[(tag, t, "decl")], per[(tag, t, "qa")]
    MD.append(f"| {LABEL[tag]} | {int(100 * t)}% | {f(d)} | {f(q)} | "
              f"{', '.join(f'{x:+.1f}' for x in d['samples'])} | {', '.join(f'{x:+.1f}' for x in q['samples'])} |")
MD += ["", "| pooled | mean | 95% interval | 90% interval | smallest margin rejected | equivalent within 1.5? |",
       "|---|---|---|---|---|---|"]
for name in ("paper", "new", "all"):
    v = TP[name]
    MD.append(f"| {name} | {v['diff']:+.2f} | {v['lo']:+.2f} to {v['hi']:+.2f} | {v['lo90']:+.2f} to {v['hi90']:+.2f} | "
              f"{v['eq_bound_smallest']:.2f} | {'yes' if v['equivalent_at_margin'] else 'no'} |")
for name in ("paper_decl", "paper_qa", "new_decl", "new_qa"):
    v = TP[name]
    MD.append(f"| {name} | {v['diff']:+.2f} | {v['lo']:+.2f} to {v['hi']:+.2f} | {v['lo90']:+.2f} to {v['hi90']:+.2f} | | |")
MD += ["", "Paper models: the 07 values (+0.67, 95% +0.18 to +1.14, bound 1.06) are recomputed here with a different "
       "random stream; small differences in the interval ends are bootstrap noise.", ""]

# ---------------------------------------------------------------- 3. Holm counts for every contrast family
FAM = {"C4 repair vs none": ("none", "c4"), "Repair channel": ("c4", "rep"), "Selection channel": ("c4", "sel"),
       "Selection, no repair": ("none", "selnone"), "Both channels": ("c4", "both"),
       "Truth (declarative), sample 0": ("dcf", "both"), "Truth (question-answer), sample 0": ("qacf", "qa"),
       "Format (QA - declarative)": ("both", "qa"), "Entities (real - made-up)": ("syn", "both"),
       "Relations (tested - other)": ("other", "both"), "KG statements - Wikipedia": ("wiki", "both"),
       "Anchoring": ("both", "anch")}
HOLM = {}
MD += ["## 3. Uncorrected and Holm-corrected counts (family = one contrast over its settings)", "",
       "| contrast | query | models | settings | sig. + | sig. - | Holm + | Holm - |", "|---|---|---|---|---|---|---|---|"]
for qname in ("question", "cloze"):
    for group, cells in (("paper", PCELLS), ("new", NCELLS)):
        for name, (a, bb) in FAM.items():
            res = []
            for tag, t in cells:
                if qname == "question":
                    xa, xb, m = B[tag][0][f"{t}|{K[a]}"]["test_q"], B[tag][0][f"{t}|{K[bb]}"]["test_q"], DQ[tag]
                else:
                    xa, xb, m = cloze_bits(tag, t, a), cloze_bits(tag, t, bb), DC[tag]
                    if len(xa) == 0 or len(xb) == 0:
                        continue
                res.append(summarize(*boot_diff(xa, xb, m)))
            if not res:
                continue
            rej = holm(np.array([r["p"] for r in res]))
            row = {"n": len(res), "sig_pos": sum(r["sig"] and r["diff"] > 0 for r in res),
                   "sig_neg": sum(r["sig"] and r["diff"] < 0 for r in res),
                   "holm_pos": int(sum(j and r["diff"] > 0 for j, r in zip(rej, res))),
                   "holm_neg": int(sum(j and r["diff"] < 0 for j, r in zip(rej, res)))}
            HOLM[f"{qname}|{group}|{name}"] = row
            MD.append(f"| {name} | {qname} | {group} | {row['n']} | {row['sig_pos']} | {row['sig_neg']} | "
                      f"{row['holm_pos']} | {row['holm_neg']} |")
OUT["holm"] = HOLM
MD += ["", "p-values are two-sided paired-bootstrap p-values (10,000 draws over test facts, floor 1e-4). Holm controls "
       "the family-wise error at 5% within each row.", ""]

(P.TABLES / "stats.json").write_text(json.dumps(OUT, indent=1))
(P.REPORTS / "stats.md").write_text("\n".join(MD) + "\n")
print("\n".join(MD))
