"""Width check, summary: estimator bias on synthetic clouds, effect on widths, sensitivity to sample size.

python scripts/analysis/widths.py  ->  results/width_check/widths_<tag>.json, outputs/reports/widths.md,
                                     outputs/figures/e1_synthetic.png, outputs/figures/e2_layers.png
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import spearmanr

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kgcal import paths as P            # noqa: E402
from kgcal import model_ops as MO      # noqa: E402

RES = P.WIDTHS
TAGS = [("qwen15b", "Qwen2.5-1.5B"), ("olmo1b", "OLMo-2-1B"), ("qwen7b", "Qwen2.5-7B"), ("olmo7b", "OLMo-2-7B")]
EST = ("code", "corrected", "gride", "twonn")
md = ["# GRIDE check (generated by analyze_gride.py)", ""]


def widths_for(dims, N, f):
    a = MO.alpha_for_fraction(list(dims), N, f)
    return a, np.array(MO.widths(list(dims), a, N))


def moved(wa, wb, N):
    """Share of all FFN units that change layer between two width vectors with (about) the same total."""
    return float(np.abs(wa - wb).sum() / 2 / (len(wa) * N))


# ---------------------------------------------------------------- E1
e1 = json.loads((RES / "e1_synthetic.json").read_text())
md += ["## E1: synthetic clouds of known dimension (2,200 points, mean of 3 seeds)", "",
       "| family | true d | code | corrected | GRIDE-MLE | TWO-NN | code / GRIDE |", "|---|---|---|---|---|---|---|"]
for fam in ("cube", "gauss", "sphere"):
    for d in (2, 4, 8, 16, 32, 64):
        r = [x for x in e1["rows"] if x["family"] == fam and x["d"] == d]
        m = {k: np.mean([x[k] for x in r]) for k in EST}
        md.append(f"| {fam} | {d} | {m['code']:.2f} | {m['corrected']:.2f} | {m['gride']:.2f} | {m['twonn']:.2f} | "
                  f"{m['code'] / m['gride']:.3f} |")
md.append("")

# ---------------------------------------------------------------- E2 / E3
summary = {}
for tag, label in TAGS:
    p = RES / f"{tag}_dims.json"
    if not p.exists():
        continue
    R = json.loads(p.read_text())
    N, L = R["N"], R["L"]
    dc = np.array([e["code"] for e in R["layers"]])
    dsk = np.array([e["code_sklearn"] for e in R["layers"]])
    dg = np.array([e["gride"] for e in R["layers"]])
    dt = np.array([e["twonn"] for e in R["layers"]])
    ratio = dc / dg
    row = {"repro_gap": R["repro_gap"], "gpu_vs_sklearn": float(np.max(np.abs(dc - dsk))),
           "ratio_mean": float(ratio.mean()), "ratio_min": float(ratio.min()), "ratio_max": float(ratio.max()),
           "spearman_code_gride": float(spearmanr(dc, dg).statistic), "d_code": dc.tolist(), "d_gride": dg.tolist()}
    # median scale chosen per layer by each estimator
    ks = np.array(R["layers"][0]["ks"])
    row["median_k_code"] = [int(ks[np.argsort(e["per_k"]["code"])[len(ks) // 2]]) for e in R["layers"]]
    row["budgets"] = {}
    for f in (0.7, 0.5):
        ac, wc = widths_for(dc, N, f)
        ag, wg = widths_for(dg, N, f)
        at, wt = widths_for(dt, N, f)
        row["budgets"][f] = {"alpha_code": ac, "alpha_gride": ag, "keep_code": float(wc.sum() / (L * N)),
                             "keep_gride": float(wg.sum() / (L * N)), "moved_gride": moved(wc, wg, N),
                             "moved_twonn": moved(wc, wt, N), "max_abs_dM_gride": int(np.abs(wc - wg).max()),
                             "max_rel_dM_gride": float((np.abs(wc - wg) / wc).max()),
                             "whole_layers_code": int((wc == N).sum()), "whole_layers_gride": int((wg == N).sum()),
                             "w_code": wc.tolist(), "w_gride": wg.tolist()}
    # unit-subsample seeds (paper setting): spread of d and of widths
    seeds = R["subsample_seeds"]
    for est in ("code", "gride"):
        D = np.array([[x[est] for x in seeds[s]] for s in seeds])          # seeds x layers
        row[f"seed_cv_{est}"] = float((D.std(0, ddof=1) / D.mean(0)).mean())
        w = [widths_for(D[i], N, 0.7)[1] for i in range(D.shape[0])]
        row[f"seed_moved_{est}"] = float(np.mean([moved(w[i], w[j], N) for i in range(3) for j in range(i + 1, 3)]))
    # sample size sweep: median over layers of d / d(2048 tokens, 2200 units) and units moved at 70%
    sw = R["sweep"]
    ref = {(x["layer"]): x for x in sw if x["n_tok"] == 2048 and x["n_pts"] == 2200}
    grid = {}
    for n_tok in (512, 1024, 2048, 4096, 8192):
        for n_pts in sorted({x["n_pts"] for x in sw}):
            sub = sorted([x for x in sw if x["n_tok"] == n_tok and x["n_pts"] == n_pts], key=lambda x: x["layer"])
            if len(sub) != L:
                continue
            g = {}
            for est in ("code", "gride"):
                d = np.array([x[est] for x in sub])
                d0 = np.array([ref[l][est] for l in range(L)])
                g[f"{est}_rel"] = float(np.median(d / d0))
                g[f"{est}_moved70"] = moved(widths_for(d0, N, 0.7)[1], widths_for(d, N, 0.7)[1], N)
                g[f"{est}_spearman"] = float(spearmanr(d, d0).statistic)
            grid[f"{n_tok}x{n_pts}"] = g
    row["sweep"] = grid
    summary[tag] = row
    (RES / f"widths_{tag}.json").write_text(json.dumps(row, indent=1))

if summary:
    md += ["## E2: real FFN clouds (paper setting: 2,048 C4 tokens, 2,200 units, seed 0)", "",
           "| model | reproduces cached d | code / GRIDE per layer (mean, range) | Spearman(code, GRIDE) | "
           "units moved if widths used GRIDE, 70% / 50% | max relative change of one layer's width, 70% |",
           "|---|---|---|---|---|---|"]
    for tag, label in TAGS:
        if tag not in summary:
            continue
        r = summary[tag]
        b7, b5 = r["budgets"][0.7], r["budgets"][0.5]
        md.append(f"| {label} | gap {r['repro_gap']:.1g} | {r['ratio_mean']:.3f} ({r['ratio_min']:.3f} to {r['ratio_max']:.3f}) | "
                  f"{r['spearman_code_gride']:.3f} | {100 * b7['moved_gride']:.2f}% / {100 * b5['moved_gride']:.2f}% | "
                  f"{100 * b7['max_rel_dM_gride']:.1f}% |")
    md += ["", "Units moved = half the sum over layers of |M_l(code) - M_l(GRIDE)|, as a share of all FFN units "
           "(0% means identical widths).", "",
           "## E3: robustness of the widths (70% budget)", "",
           "| model | unit-subsample seeds: mean CV of d (code / GRIDE) | units moved between seeds (code / GRIDE) |",
           "|---|---|---|"]
    for tag, label in TAGS:
        if tag in summary:
            r = summary[tag]
            md.append(f"| {label} | {r['seed_cv_code']:.3f} / {r['seed_cv_gride']:.3f} | "
                      f"{100 * r['seed_moved_code']:.2f}% / {100 * r['seed_moved_gride']:.2f}% |")
    md += ["", "Sample size: median over layers of d relative to the paper setting, and units moved at 70% "
           "(code estimator; GRIDE in brackets).", ""]
    for tag, label in TAGS:
        if tag not in summary:
            continue
        md += [f"### {label}", "", "| tokens x units | d / d_paper | units moved | Spearman with paper d |", "|---|---|---|---|"]
        for key, g in summary[tag]["sweep"].items():
            md.append(f"| {key} | {g['code_rel']:.3f} ({g['gride_rel']:.3f}) | {100 * g['code_moved70']:.2f}% "
                      f"({100 * g['gride_moved70']:.2f}%) | {g['code_spearman']:.3f} ({g['gride_spearman']:.3f}) |")
        md.append("")
(P.REPORTS / "widths.md").write_text("\n".join(md) + "\n")
print("\n".join(md))

