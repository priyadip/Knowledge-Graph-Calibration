"""Mixture sweep: the curve and the recommendation rule fixed before the runs.

Usage:  python scripts/analysis/mixture_rule.py
For each channel (both channels, repair only, selection without repair) and KG share s in {10, 25, 50, 75}%:
G(s) = retention gain over C4/C4 (dense-known test facts, question queries, sample 0) per setting; H(s) = HellaSwag
change over C4/C4 on the 7B models. The s = 50 conditions are the paper's (MIX:KG-D|MIX:KG-D, C4|MIX:KG-D,
MIX:KG-D|none). A share s* < 50 is recommended for a channel only if (a) mean G(s*) >= 0.75 mean G(50) over the 8
settings and G(s*) >= 0.75 G(50) in at least 6 of 8, and (b) the 7B-mean HellaSwag loss at s* is at most half of the
loss at 50. The smallest qualifying share is named. Samples 1 and 2 (1B models) are reported beside, not used by the
rule. Writes outputs/tables/mixture.json and outputs/reports/mixture.md.
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from kgcal import paths as P            # noqa: E402
MODELS = [("qwen15b", "Qwen2.5-1.5B"), ("olmo1b", "OLMo-2-1B"), ("qwen7b", "Qwen2.5-7B"), ("olmo7b", "OLMo-2-7B")]
SEVEN = ("qwen7b", "olmo7b")
SHARES = [(13, "10%"), (32, "25%"), (64, "50%"), (96, "75%")]
CHANNELS = {"both": ("R{n}|R{n}", "MIX:KG-D|MIX:KG-D"), "repair": ("R0|R{n}", "C4|MIX:KG-D"),
            "selection": ("R{n}|none", "MIX:KG-D|none")}


def load(path):
    if not path.exists():
        return None, None
    bits = {k: {f: np.array([c == "1" for c in v[f]], bool) for f in v} for k, v in json.loads(path.read_text()).items()}
    recs = {}
    for line in open(path.with_name(path.name.replace("_bits.json", ".jsonl"))):
        r = json.loads(line)
        recs[f"{r['target']}|{r['cond']}"] = r
    return bits, recs


def cell(tag, t, ch, n, sfx=""):
    """(gain in points, HellaSwag change in points or None, WikiText-2 ppl) for one channel, share and setting."""
    mb, mr = load(P.MIXTURE / f"{tag}_mix{sfx}_bits.json")
    pb, pr = load(P.MERGED / f"{tag}{sfx}_bits.json")
    dense = pb["1.0|dense"]["test_q"]
    base_b, base_r = mb[f"{t}|R0|R0"]["test_q"], mr[f"{t}|R0|R0"]
    fmt, paper_key = CHANNELS[ch]
    key = f"{t}|{fmt.format(n=n)}"
    if n == 64 and key not in mb:                         # the paper's 50% condition
        if f"{t}|{paper_key}" not in pb:
            return None
        b, r = pb[f"{t}|{paper_key}"]["test_q"], pr[f"{t}|{paper_key}"]
    elif key in mb:
        b, r = mb[key]["test_q"], mr[key]
    else:
        return None
    g = 100 * (b[dense].mean() - base_b[dense].mean())
    hs = None
    if r.get("hellaswag") is not None and base_r.get("hellaswag") is not None:
        hs = 100 * (r["hellaswag"] - base_r["hellaswag"])
    return g, hs, r["ppl_wikitext2"]


CELLS = [(tag, t) for tag, _ in MODELS for t in ("0.7", "0.5")]
OUT, MD = {}, ["# Mixture sweep (generated by scripts/analysis/mixture_rule.py; do not edit)", ""]
for ch in CHANNELS:
    MD += [f"## {ch}", "", "| model | budget | " + " | ".join(f"KG {s}: gain (HS, ppl)" for _, s in SHARES) + " |",
           "|---|---|" + "---|" * len(SHARES)]
    tab = {}
    for tag, t in CELLS:
        row = []
        for n, s in SHARES:
            v = cell(tag, t, ch, n)
            tab[(tag, t, n)] = v
            row.append("--" if v is None else f"{v[0]:+.1f} ({'' if v[1] is None else f'{v[1]:+.1f}, '}{v[2]:.1f})")
        MD.append(f"| {dict(MODELS)[tag]} | {int(100 * float(t))}% | " + " | ".join(row) + " |")
    verdict = {}
    g50 = [tab[(tag, t, 64)] for tag, t in CELLS]
    h50 = [tab[(tag, t, 64)][1] for tag, t in CELLS if tag in SEVEN and tab[(tag, t, 64)] is not None]
    for n, s in SHARES:
        if n >= 64:
            continue
        gs = [tab[(tag, t, n)] for tag, t in CELLS]
        if any(v is None for v in gs + g50) or len(h50) < 4 or any(x is None for x in h50):
            verdict[s] = "not decidable yet (missing runs or zero-shot scores)"
            continue
        hs = [tab[(tag, t, n)][1] for tag, t in CELLS if tag in SEVEN]
        if any(x is None for x in hs):
            verdict[s] = "not decidable yet (missing zero-shot scores)"
            continue
        mean_ok = np.mean([v[0] for v in gs]) >= 0.75 * np.mean([v[0] for v in g50])
        count = sum(a[0] >= 0.75 * b[0] for a, b in zip(gs, g50))
        loss_s, loss_50 = -np.mean(hs), -np.mean(h50)
        hs_ok = loss_s <= 0.5 * loss_50 if loss_50 > 0 else True
        verdict[s] = {"mean_gain": float(np.mean([v[0] for v in gs])), "mean_gain_50": float(np.mean([v[0] for v in g50])),
                      "settings_at_75pct": int(count), "hs_loss": float(loss_s), "hs_loss_50": float(loss_50),
                      "qualifies": bool(mean_ok and count >= 6 and hs_ok)}
    rec = next((s for n, s in SHARES if n < 64 and isinstance(verdict.get(s), dict) and verdict[s]["qualifies"]), None)
    OUT[ch] = {"verdict": verdict, "recommended_share": rec}
    MD += ["", f"Rule for {ch}: " + "; ".join(
        f"{s}: {v if isinstance(v, str) else ('QUALIFIES' if v['qualifies'] else 'fails')} "
        + ("" if isinstance(v, str) else f"(mean gain {v['mean_gain']:+.1f} vs {v['mean_gain_50']:+.1f} at 50%, "
                                         f"{v['settings_at_75pct']}/8 settings at >= 75%, HellaSwag loss {v['hs_loss']:.1f} "
                                         f"vs {v['hs_loss_50']:.1f})") for s, v in verdict.items())
           + f". Recommended share: {rec or 'none'}.", ""]

# other calibration samples of the 1B models, both channels, beside the rule
MD += ["## Other calibration samples (1B models, both channels; not used by the rule)", "",
       "| model | budget | sample | " + " | ".join(f"KG {s}" for _, s in SHARES) + " |", "|---|---|---|" + "---|" * len(SHARES)]
for tag in ("qwen15b", "olmo1b"):
    for t in ("0.7", "0.5"):
        for sfx, lab in (("", "0"), ("_cs1", "1"), ("_cs2", "2")):
            vals = []
            for n, _ in SHARES:
                try:
                    v = cell(tag, t, "both", n, sfx)
                except (TypeError, KeyError):
                    v = None
                vals.append("--" if v is None else f"{v[0]:+.1f}")
            MD.append(f"| {dict(MODELS)[tag]} | {int(100 * float(t))}% | {lab} | " + " | ".join(vals) + " |")
(P.TABLES / "mixture.json").write_text(json.dumps(OUT, indent=1))
(P.REPORTS / "mixture.md").write_text("\n".join(MD) + "\n")
print("\n".join(MD))
